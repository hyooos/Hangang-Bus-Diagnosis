"""한강버스 운항 시간표(2026.8.15 적용, 주말·공휴일 동일)를 정형화.
출처: hgbus.co.kr/images/sub/information/schedule_img4_v260815.jpg (누리집 운항시간 페이지 이미지 판독)
도착시각은 표에 있으면 그대로(마곡·잠실 종점), 없으면 직전 출발 + 공식 구간시간(노선도 표기)으로 추정."""
import pandas as pd

SEG = {('마곡', '망원'): 21, ('망원', '여의도'): 26, ('여의도', '압구정'): 29, ('압구정', '옥수'): 9,
       ('옥수', '서울숲'): 15, ('서울숲', '뚝섬'): 14, ('뚝섬', '잠실'): 15}
def seg(a, b):
    order = ['마곡', '망원', '여의도', '압구정', '옥수', '서울숲', '뚝섬', '잠실']
    i, j = sorted([order.index(a), order.index(b)])
    return sum(SEG.get((order[k], order[k + 1]), 0) for k in range(i, j))

# (방향, [ (선착장, 출발 or None, 도착 or None), ... ]) — 편별
W_E = [('11:20', '11:42'), ('12:20', '12:42'), ('13:20', '13:42'), ('14:20', '14:42'), ('15:00', '15:22'),
       ('15:30', '15:52'), ('16:00', '16:22'), ('17:00', '17:22'), ('17:40', '18:02'), ('18:40', '19:02')]
W_W = [('12:12', '12:34', '12:53'), ('13:12', '13:34', '13:53'), ('14:12', '14:34', '14:53'), ('15:12', '15:34', '15:53'),
       ('16:52', '17:14', '17:33'), ('17:52', '18:14', '18:33'), ('18:32', '18:54', '19:13'), ('19:32', '19:54', '20:13'),
       ('20:25', '20:48', '21:09'), ('20:55', '21:18', '21:39')]
E_E = [('12:38', '옥수', '13:13', '13:31', '13:49', '14:03'), ('13:35', '압구정', '14:07', '14:28', '14:46', '15:00'),
       ('14:40', '옥수', '15:15', '15:33', '15:51', '16:05'), ('15:40', '압구정', '16:12', '16:33', '16:51', '17:05'),
       ('16:00', '옥수', '16:35', '16:53', '17:11', '17:25'), ('16:30', '압구정', '17:02', '17:23', '17:41', '17:55'),
       ('17:08', '옥수', '17:43', '18:01', '18:19', '18:33'), ('18:05', '압구정', '18:37', '18:58', '19:16', '19:30'),
       ('19:05', '옥수', '19:40', '19:58', '20:16', '20:30'), ('20:05', '압구정', '20:37', '20:58', '21:16', '21:30')]
E_W = [('11:00', '11:17', '11:35', '옥수', '11:52'), ('12:00', '12:17', '12:35', '압구정', '12:55'),
       ('13:00', '13:17', '13:35', '옥수', '13:52'), ('14:00', '14:17', '14:35', '압구정', '14:55'),
       ('15:30', '15:47', '16:05', '옥수', '16:22'), ('16:30', '16:47', '17:05', '압구정', '17:25'),
       ('17:30', '17:47', '18:05', '옥수', '18:22'), ('18:30', '18:47', '19:05', '압구정', '19:25'),
       ('18:50', '19:07', '19:25', '옥수', '19:42'), ('19:20', '19:37', '19:55', '압구정', '20:15')]

m = lambda s: int(s[:2]) * 60 + int(s[3:])
hm = lambda x: f'{int(x)//60:02d}:{int(x)%60:02d}'
rows = []
def add(route, dirc, trip, stops):  # stops: [(name, dep_min or None, arr_min or None, arr_src)]
    for k, (nm, dep, arr, src) in enumerate(stops, 1):
        nxt = stops[k][0] if k < len(stops) else None
        rows.append(dict(ROUTE_CD=route, DIR_CD=dirc, DAY_TYPE='전체', TRIP_NO=trip, STOP_SEQ=k, STOP_NM=nm,
                         ARR_HM=hm(arr) if arr is not None else '', ARR_SRC=src,
                         DEP_HM=hm(dep) if dep is not None else '',
                         SEG_MIN=seg(nm, nxt) if nxt else '', EXPRESS_YN='N'))
for i, (a, b) in enumerate(W_E, 1):
    add('서측', '여의도행', i, [('마곡', m(a), None, ''), ('망원', m(b), None, ''), ('여의도', None, m(b) + seg('망원', '여의도'), '추정')])
for i, (a, b, c) in enumerate(W_W, 1):
    add('서측', '마곡행', i, [('여의도', m(a), None, ''), ('망원', m(b), None, ''), ('마곡', None, m(c), '시간표')])
for i, (a, via, b, c, d, e) in enumerate(E_E, 1):
    add('동측', '잠실행', i, [('여의도', m(a), None, ''), (via, m(b), None, ''), ('서울숲', m(c), None, ''),
                            ('뚝섬', m(d), None, ''), ('잠실', None, m(e), '시간표')])
for i, (a, b, c, via, d) in enumerate(E_W, 1):
    add('동측', '여의도행', i, [('잠실', m(a), None, ''), ('뚝섬', m(b), None, ''), ('서울숲', m(c), None, ''),
                             (via, m(d), None, ''), ('여의도', None, m(d) + seg(via, '여의도'), '추정')])
df = pd.DataFrame(rows)
df.to_csv('data/hangang_timetable.csv', index=False, encoding='utf-8-sig')
